// Build the complete data structure
let allItems = [];
const allDims = [];

for (const [key, dim] of Object.entries(facets)) {
  const fwdNames = dim.F;
  const itemsArr = dim.items;
  const facetList = [];
  let total = 0;

  for (let fi = 0; fi < 6; fi++) {
    const facetItems = itemsArr[fi]; // 10 items per facet
    const fIndices = [];
    const fRev = [];
    for (let ii = 0; ii < 10; ii++) {
      const idx = allItems.length;
      allItems.push(facetItems[ii]);
      fIndices.push(idx);
      if (ii >= 5) fRev.push(idx); // items 5-9 are reverse
      total++;
    }
    facetList.push({
      name: fwdNames[fi],
      indices: fIndices,
      r: fRev,
    });
  }

  allDims.push({
    name: dim.name,
    items: facetList.map(f => f.indices).flat(),
    r: facetList.map(f => f.r).flat(),
    max: 300, // 60 items x 5
    high: dim.name.split(' ')[0],
    low: dim.name.split(' ')[2],
    desc: dim.desc,
    higher: '—',
    facets: facetList,
  });
}

